function Fail([string]$msg) { Write-Host "ERROR: $msg" -ForegroundColor Red; exit 1 }
function Step([string]$msg) { Write-Host "==> $msg" -ForegroundColor Cyan }

function Expand-Patch([string]$b64, [string]$path) {
    $bytes = [Convert]::FromBase64String(($b64 -replace '\s', ''))
    $in = New-Object System.IO.MemoryStream(,$bytes)
    $gz = New-Object System.IO.Compression.GZipStream($in, [System.IO.Compression.CompressionMode]::Decompress)
    $out = New-Object System.IO.MemoryStream
    $gz.CopyTo($out)
    $gz.Dispose()
    [System.IO.File]::WriteAllBytes($path, $out.ToArray())   # raw bytes, so the patch keeps its LF endings
}

if (-not (Get-Command git -ErrorAction SilentlyContinue)) { Fail 'git is not on PATH.' }

$root = & git -C $Repo rev-parse --show-toplevel 2>$null
if ($LASTEXITCODE -ne 0 -or -not $root) { Fail "$Repo is not inside a git repository." }
$root = ([string]$root).Trim()
if (-not (Test-Path (Join-Path $root 'sim\data\modules\ravenmoor.json'))) {
    Fail "$root does not look like CppDnD (sim\data\modules\ravenmoor.json is missing)."
}

# --ignore-whitespace copes with CRLF checkouts.
$flags = @('--ignore-whitespace', '--whitespace=nowarn')
$tmp = Join-Path ([System.IO.Path]::GetTempPath()) ('cppdnd-fix-' + [guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory -Path $tmp | Out-Null

try {
    foreach ($name in $embedded.Keys) {
        Step $name
        $patch = Join-Path $tmp ($name + '.patch')
        Expand-Patch $embedded[$name] $patch

        & git -C $root apply --check -R @flags $patch 2>$null
        if ($LASTEXITCODE -eq 0) { Write-Host '    already applied, skipping'; continue }

        & git -C $root apply --check @flags $patch
        if ($LASTEXITCODE -ne 0) {
            Fail "$name does not apply cleanly. Commit or stash local edits to the files it touches, and check you are on the commit it was made against (Fix resources folder name, add demo image)."
        }
        & git -C $root apply @flags $patch
        if ($LASTEXITCODE -ne 0) { Fail "git apply failed for $name." }
        Write-Host '    applied'
    }
}
finally {
    Remove-Item -Recurse -Force $tmp -ErrorAction SilentlyContinue
}

Step 'changed files'
& git -C $root status --short

if ($SkipTests) { Write-Host 'Done, tests skipped.' -ForegroundColor Green; exit 0 }

$test = Join-Path $root 'test.ps1'
if (-not (Test-Path $test)) { Fail 'test.ps1 not found in the repo root.' }

Step 'test.ps1 (build, then every test)'
$global:LASTEXITCODE = 0
Push-Location $root
try { & $test } finally { Pop-Location }
